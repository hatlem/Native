const LANDING = { en: EN, no: NO, sv: SV, da: DA };

let total = 0;
for (const [locale, namespace] of Object.entries(LANDING)) {
  const file = path.join(ROOT, "src/messages", `${locale}.json`);
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  if (data.landing) {
    console.log(`${locale}: landing already exists — skipping`);
    continue;
  }
  data.landing = namespace;
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log(`${locale}: landing added`);
  total++;
}
console.log(`updated: ${total}`);
